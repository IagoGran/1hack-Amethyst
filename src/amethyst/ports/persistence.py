"""Local repositories: save is upsert, missing load raises NOT_FOUND.

Delete is idempotent; list order is by ID. Values are detached snapshots.
Durable implementations retain values until explicit deletion, across restarts.
"""

from typing import Protocol

from amethyst.domain.contracts import Connection, Conversation, Skill


class ConversationRepository(Protocol):
    async def save(self, value: Conversation) -> None: ...
    async def load(self, item_id: str) -> Conversation: ...
    async def list(self) -> tuple[Conversation, ...]: ...
    async def delete(self, item_id: str) -> None: ...


class SkillRepository(Protocol):
    async def save(self, value: Skill) -> None: ...
    async def load(self, item_id: str) -> Skill: ...
    async def list(self) -> tuple[Skill, ...]: ...
    async def delete(self, item_id: str) -> None: ...


class ConnectionRepository(Protocol):
    async def save(self, value: Connection) -> None: ...
    async def load(self, item_id: str) -> Connection: ...
    async def list(self) -> tuple[Connection, ...]: ...
    async def delete(self, item_id: str) -> None: ...
